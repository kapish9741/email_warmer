// Renders an example 20-message exchange (10 threads, A → B then B → A) from the real template library and
// selector, so the sample always matches what the worker sends. Usage: npm run templates:sample
import { writeFileSync } from "node:fs"
import { join } from "node:path"
import { buildMessageBody, buildReply } from "../src/modules/warmup/message-content"
import { buildTemplateContext, getTemplate, renderTemplate, selectReply, selectTemplate } from "../src/modules/warmup/templates"

const MAILBOX = { A: "jordan.lee@example.com", B: "casey.morgan@example.org" }
const config = { timezone: "America/New_York", activeStartHour: 9, activeEndHour: 17, dailyLimit: 20 }

// Small seeded PRNG so the sample is reproducible.
let seed = 20261021
const random = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31)

const out: string[] = [
  "# Sample conversation sequence",
  "",
  `Generated by \`npm run templates:sample\` from the template library. Mailbox A (warmup) is \`${MAILBOX.A}\`,`,
  `Mailbox B (target) is \`${MAILBOX.B}\`, time zone ${config.timezone}, sending window 09:00–17:00.`,
  "Each thread is a message from A followed by B's reply to it, which is the order the worker sends them in.",
  "When sent, a reply also quotes the start of the original below the footer; that quote is left out here.",
  "",
]

const recent: string[] = []
let n = 0
let at = new Date("2026-10-19T13:20:00Z") // Monday, 09:20 in New York
for (let thread = 1; thread <= 10; thread++) {
  const template = selectTemplate(recent, { random })
  recent.unshift(template.id)
  const testId = `tst_sample${String(thread).padStart(2, "0")}`
  const message = { testId, templateId: template.id, scheduledAt: at, from: MAILBOX.A, to: MAILBOX.B }
  const ctx = buildTemplateContext({ ...config, senderEmail: MAILBOX.A, recipientEmail: MAILBOX.B, at, testId })
  const subject = renderTemplate(template.subject, ctx)
  const body = buildMessageBody(message, config)
  const reply = selectReply(template.id)!
  const replyBody = buildReply(message, config, { subject, date: at })

  const starterNo = ++n
  out.push(
    `## Message ${starterNo}`,
    "",
    `- **From → To:** Mailbox A → Mailbox B`,
    `- **Subject:** ${subject}`,
    `- **Category:** ${template.category} (${template.purpose.toLowerCase()}), template \`${template.id}\``,
    `- **Conversation:** starts thread T${thread}`,
    `- **Message-ID:** \`<${testId}.a@example.com>\``,
    "",
    "```text",
    body,
    "```",
    "",
  )
  out.push(
    `## Message ${++n}`,
    "",
    `- **From → To:** Mailbox B → Mailbox A`,
    `- **Subject:** Re: ${subject}`,
    `- **Category:** reply (${reply.kind}), template \`${reply.id}\``,
    `- **Conversation:** replies to message ${starterNo} in thread T${thread} (In-Reply-To \`<${testId}.a@example.com>\`)`,
    `- **Message-ID:** \`<${testId}.b@example.org>\``,
    "",
    "```text",
    replyBody.split("\nOn ")[0].trimEnd(),
    "```",
    "",
  )
  // Next thread later the same day, or the next morning once past the window.
  at = new Date(at.getTime() + (90 + Math.floor(random() * 120)) * 60_000)
  const hour = Number(new Intl.DateTimeFormat("en-US", { hour: "numeric", hourCycle: "h23", timeZone: config.timezone }).format(at))
  if (hour >= 16) at = new Date(at.getTime() + (24 - hour + 9) * 3_600_000)
  if (!getTemplate(template.id)) throw new Error("unknown template")
}

const file = join(__dirname, "..", "docs", "sample-conversation.md")
writeFileSync(file, out.join("\n"))
console.log(`Wrote ${n} messages to ${file}`)
