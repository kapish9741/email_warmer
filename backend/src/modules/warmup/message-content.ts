// Truthful, controlled content (BACKEND.md §18). No forged headers; the real SMTP server signs the message.
// Templates live in ./templates; messages created before templates existed (templateId = null) keep the original text.

import { prisma } from "../../db/prisma"
import {
  buildTemplateContext,
  footer,
  getTemplate,
  RECENT_TEMPLATE_WINDOW,
  renderTemplate,
  selectReply,
  selectTemplate,
  TEST_CATEGORIES,
  WARMUP_CATEGORIES,
} from "./templates"

interface ContentConfig {
  timezone: string
  activeStartHour: number
  activeEndHour: number
  dailyLimit: number
}

interface ContentMessage {
  testId: string
  templateId: string | null
  scheduledAt: Date
  from: string
  to: string
}

export function buildSubject(testId: string): string {
  return `Deliverability Test ${testId}`
}

export function buildBody(testId: string): string {
  return [
    "Hello,",
    "",
    "This is a controlled email deliverability test generated by the",
    "email warming application.",
    "",
    `Test ID: ${testId}`,
    "",
    "Regards",
  ].join("\n")
}

function contextFor(message: Pick<ContentMessage, "testId" | "scheduledAt">, config: ContentConfig, sender: string, recipient: string, originalSubject?: string) {
  return buildTemplateContext({
    senderEmail: sender,
    recipientEmail: recipient,
    at: message.scheduledAt,
    timezone: config.timezone,
    activeStartHour: config.activeStartHour,
    activeEndHour: config.activeEndHour,
    dailyLimit: config.dailyLimit,
    testId: message.testId,
    originalSubject,
  })
}

/**
 * Chooses the template for a new message and renders its subject. Templates used by this config's recent
 * messages are avoided, so the same one isn't repeated while alternatives exist.
 */
export async function planContent(input: {
  configId: string
  type: "WARMUP" | "TEST"
  config: ContentConfig
  testId: string
  scheduledAt: Date
  from: string
  to: string
  /** Templates already chosen in the same batch that aren't saved yet, newest first. */
  pendingIds?: string[]
}): Promise<{ templateId: string; subject: string }> {
  const recent = await prisma.warmupMessage.findMany({
    where: { warmupConfigId: input.configId, templateId: { not: null } },
    orderBy: { createdAt: "desc" },
    take: RECENT_TEMPLATE_WINDOW,
    select: { templateId: true },
  })
  const template = selectTemplate([...(input.pendingIds ?? []), ...recent.map((m) => m.templateId)], {
    categories: input.type === "TEST" ? TEST_CATEGORIES : WARMUP_CATEGORIES,
  })
  const context = contextFor({ testId: input.testId, scheduledAt: input.scheduledAt }, input.config, input.from, input.to)
  return { templateId: template.id, subject: renderTemplate(template.subject, context) }
}

/** Body for an outgoing A → B message. */
export function buildMessageBody(message: ContentMessage, config: ContentConfig): string {
  const template = getTemplate(message.templateId)
  if (!template) return buildBody(message.testId)
  return renderTemplate(template.body, contextFor(message, config, message.from, message.to)) + "\n" + footer(message.testId)
}

function quote(originalText: string | undefined) {
  return (originalText ?? "")
    .trim()
    .split("\n")
    .slice(0, 12)
    .map((line) => `> ${line}`)
    .join("\n")
}

export function buildReplyBody(testId: string, originalText: string | undefined): string {
  const quoted = quote(originalText)
  return [
    "Hello,",
    "",
    `This reply confirms that deliverability test ${testId} was received`,
    "in the target mailbox.",
    "",
    "Regards",
    "",
    ...(quoted ? [quoted] : []),
  ].join("\n")
}

/**
 * Body for B's reply to A. Uses the reply written for the original message's template, so it answers what was
 * actually sent; sender and recipient are swapped because the reply travels B → A.
 */
export function buildReply(
  message: ContentMessage,
  config: ContentConfig,
  original: { text?: string; subject?: string; date?: Date },
): string {
  const reply = selectReply(message.templateId)
  if (!reply) return buildReplyBody(message.testId, original.text)

  const context = contextFor(message, config, message.to, message.from, original.subject ?? "")
  const quoted = quote(original.text)
  const when = original.date ?? message.scheduledAt
  const attribution = `On ${new Intl.DateTimeFormat("en-US", { dateStyle: "medium", timeStyle: "short", timeZone: config.timezone }).format(when)}, ${message.from} wrote:`
  return [renderTemplate(reply.body, context), footer(message.testId), ...(quoted ? ["", attribution, quoted] : [])].join("\n")
}
